export const EQUIPMENT_BY_ORDER = [...EQUIPMENT].sort((a, b) => a.order - b.order);

export const EQUIPMENT_MACHINING = EQUIPMENT_BY_ORDER.filter(
  (item) => !item.category || item.category === "machining",
);

export const EQUIPMENT_MATERIALS = EQUIPMENT_BY_ORDER.filter(
  (item) => item.category === "materials",
);

export const EQUIPMENT_CASTING = EQUIPMENT_BY_ORDER.filter(
  (item) => item.category === "casting",
);

export function getEquipmentBySlug(slug: string) {
  return EQUIPMENT.find((item) => item.slug === slug);
}

export function getOtherEquipment(slug: string) {
  return EQUIPMENT_BY_ORDER.filter((item) => item.slug !== slug);
}
