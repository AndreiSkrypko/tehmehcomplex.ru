function Replace-All([string]$find, [string]$replace) {
  $range = $doc.Content
  $null = $range.Find.Execute(
    $find, $false, $true, $false, $false, $false, $true, 1, $true, $replace, 2
  )
  while ($range.Find.Execute(
    $find, $false, $true, $false, $false, $false, $true, 1, $true, $replace, 2
  )) {}
}

