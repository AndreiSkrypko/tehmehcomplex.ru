function p(text, opts = {}) {
  return new Paragraph({
    alignment: opts.center ? AlignmentType.CENTER : AlignmentType.JUSTIFIED,
    spacing: { after: opts.after ?? 120 },
    children: [new TextRun({ text, size: opts.size ?? 24, bold: opts.bold })],
  });
}

function cellPs(lines) {
  return lines.map((text, i) =>
    new Paragraph({
      spacing: { after: i === lines.length - 1 ? 80 : 40 },
      children: [
        new TextRun({
          text,
          size: 24,
          bold: text.startsWith("ИСПОЛНИТЕЛЬ") || text.startsWith("ЗАКАЗЧИК"),
        }),
      ],
    }),
  );
}

function twoColumns(leftLines, rightLines) {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: noBorders,
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            borders: noBorders,
            children: cellPs(leftLines),
          }),
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            borders: noBorders,
            children: cellPs(rightLines),
          }),
        ],
      }),
    ],
  });
}

function section(title) {
  return new Paragraph({
    spacing: { before: 200, after: 120 },
    children: [new TextRun({ text: title, bold: true, size: 24 })],
  });
}

